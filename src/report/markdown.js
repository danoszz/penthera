import { REASONS } from "../../lib/coverage.js";
import { exitNote } from "./exit.js";
import { mdInline } from "./md-escape.js";
import { footerLines } from "./footer.js";
import { giantsMarkdown, foundByText } from "./giants.js";

const SEV_ORDER = { critical: 0, high: 1, medium: 2, low: 3, info: 4 };
const SEV_TAG = {
  critical: "[CRIT]",
  high: "[HIGH]",
  medium: "[MED]",
  low: "[LOW]",
  info: "[INFO]",
};

function sortFindings(findings) {
  return [...(findings || [])].sort(
    (a, b) => (SEV_ORDER[a.severity] ?? 5) - (SEV_ORDER[b.severity] ?? 5),
  );
}

function countBySeverity(findings) {
  const counts = { critical: 0, high: 0, medium: 0, low: 0, info: 0 };
  for (const f of findings || []) {
    if (counts[f.severity] != null) counts[f.severity]++;
  }
  return counts;
}

const mdEscape = mdInline;

/**
 * Generate Markdown report content from scan result.
 */
export function formatMarkdownReport(result, opts = {}) {
  const findings = sortFindings(result.findings);
  const counts = countBySeverity(findings);
  // TODO(good-first-issue): the "0.2.0" fallback is stale; read the version from package.json instead.
  const version = opts.version || "0.2.0";
  const lines = [];

  lines.push(`# Penthera Security Report`);
  lines.push("");
  lines.push(`> Generated by [Penthera](https://github.com/danoszz/penthera) v${version}`);
  lines.push("");

  lines.push("## Executive summary");
  lines.push("");
  lines.push(`| | |`);
  lines.push(`|---|---|`);
  lines.push(`| **Target** | \`${result.target || "unknown"}\` |`);
  lines.push(`| **Scan time** | ${result.timestamp?.replace("T", " ").slice(0, 19) || "-"} UTC |`);
  // TODO(good-first-issue): a missing duration prints ", "; print "-" like the other empty cells and add a test.
  lines.push(`| **Duration** | ${result.duration ? `${(result.duration / 1000).toFixed(1)}s` : ", "} |`);
  lines.push(`| **Mode** | ${result.modes?.join(", ") || result.mode || "-"} |`);
  // Only a URL scan reaches anything; a repo, deps or agents scan has nothing to report here.
  const modes = result.modes || [result.mode];
  if (modes.includes("url")) lines.push(`| **Reachable** | ${result.reachable ? "Yes" : "No"} |`);
  if (result.profile) lines.push(`| **Profile** | ${result.profile} |`);
  if (result.agents) {
    lines.push(`| **Agent config grade** | ${result.agents.grade ? `**${result.agents.grade}** (${result.agents.score}/100)` : "none, nothing found to assess"} |`);
    const inv = result.agents.inventory || {};
    lines.push(`| **Agent config found** | ${inv.skills || 0} skills, ${inv.mcpServers || 0} MCP servers, ${inv.hooks || 0} hooks, ${inv.plugins || 0} plugins |`);
    if (result.agents.lock) lines.push(`| **penthera.lock** | ${result.agents.lock.status} |`);
    for (const n of result.agents.notChecked || []) lines.push(`| **Not read** | ${mdInline(n)} |`);
  }
  lines.push("");

  const total = findings.length;
  const note = exitNote(result);
  if (total === 0 && !note && result.agents && result.agents.grade == null) {
    lines.push("**Nothing to assess: no agent config was read. This is not a clean result.**");
    lines.push("");
  } else if (total === 0) {
    lines.push(note ? `**${mdInline(note)}**` : "**No security findings detected.**");
    lines.push("");
  } else {
    lines.push(
      `Found **${total}** issue(s): ` +
      `${counts.critical} critical · ${counts.high} high · ${counts.medium} medium · ` +
      `${counts.low} low · ${counts.info} info`,
    );
    lines.push("");
    if (note) lines.push(`**${mdInline(note)}**`, "");

    if (counts.critical > 0 || counts.high > 0) {
      lines.push("> **Action required**, critical or high severity issues should be fixed before production deployment.");
      lines.push("");
    }
  }

  if (opts.baseline) {
    lines.push("## Baseline comparison");
    lines.push("");
    lines.push(`Compared against: \`${opts.baseline.path}\``);
    lines.push("");
    lines.push(`| Status | Count |`);
    lines.push(`|--------|-------|`);
    lines.push(`| New findings | ${opts.baseline.newCount} |`);
    lines.push(`| Resolved since baseline | ${opts.baseline.resolvedCount} |`);
    lines.push(`| Unchanged | ${opts.baseline.unchangedCount} |`);
    lines.push("");
  }

  // No probe maps to a WSTG area in a deps or agents scan: leave the empty table out.
  const wstg = buildWstgCoverage(result, result.profile || opts.profile || "standard");
  if (wstg.wstgExercised.length) lines.push(formatWstgMarkdown(wstg));

  if (result.compliance) {
    lines.push(formatComplianceMarkdown(result.compliance));
  }

  if (result.deps) {
    lines.push(formatDepsMarkdown(result.deps));
  }

  if (result.fingerprint) {
    lines.push("## Technology fingerprint");
    lines.push("");
    const fp = result.fingerprint;
    if (fp.framework) lines.push(`- **Framework:** ${fp.framework}`);
    if (fp.server) lines.push(`- **Server:** ${fp.server}`);
    if (fp.cdn) lines.push(`- **CDN:** ${fp.cdn}`);
    lines.push(`- **Security headers:** ${fp.security?.length ? fp.security.join(", ") : "none detected"}`);
    lines.push("");
  }

  if (result.openapi?.specUrl) {
    lines.push("## API surface");
    lines.push("");
    lines.push(`- **OpenAPI spec:** ${result.openapi.specUrl}`);
    lines.push(`- **Paths documented:** ${result.openapi.pathCount || "-"}`);
    lines.push(`- **Unprotected routes (spec):** ${result.openapi.unprotectedRoutes || "-"}`);
    lines.push("");
  }

  if (total > 0) {
    lines.push("## Findings");
    lines.push("");

    const grouped = {};
    for (const f of findings) {
      const sev = f.severity || "info";
      if (!grouped[sev]) grouped[sev] = [];
      grouped[sev].push(f);
    }

    for (const sev of ["critical", "high", "medium", "low", "info"]) {
      const group = grouped[sev];
      if (!group?.length) continue;

      lines.push(`### ${SEV_TAG[sev]} ${sev.charAt(0).toUpperCase() + sev.slice(1)} (${group.length})`);
      lines.push("");
      lines.push("| Finding | URL | Confidence | Source |");
      lines.push("|---------|-----|-----------|--------|");

      for (const f of group) {
        lines.push(`| **${mdEscape(f.title)}**${f.alsoProposedBy?.length ? " (also proposed by AI)" : ""} | ${f.url ? `[link](${f.url})` : "-"} | ${f.confidence || "-"} | ${mdEscape(f.source || "-")}${foundByText(f) ? ` (${mdEscape(foundByText(f))})` : ""} |`);
      }
      lines.push("");

      for (const f of group) {
        const refs = referencesFor(f);
        if (!f.description && refs.length === 0) continue;
        lines.push(`**${f.title}**`);
        lines.push("");
        if (f.description) lines.push(f.description);
        if (f.url) lines.push(`\n- URL: ${f.url}`);
        if (f.status) lines.push(`- HTTP status: ${f.status}`);
        if (refs.length) lines.push(`- Why this matters / Sources: ${formatSourcesMarkdown(refs)}`);
        lines.push("");
      }
    }
  }

  if (result.suppressed?.length) {
    lines.push("## Suppressed findings");
    lines.push("");
    lines.push("Hidden from the findings above by `--memory`. Review these: a suppression is a decision someone made, not a fix.");
    lines.push("");
    lines.push("| Finding | Severity | Suppressed by | Reason | Id |");
    lines.push("|---------|----------|---------------|--------|----|");
    for (const f of result.suppressed) {
      const by = f.suppression?.source === "repo-file" ? "**suppressed by repo file** (`penthera.suppress.json`)" : "suppressed by local memory";
      lines.push(`| ${mdEscape(f.title)} | ${f.severity || "-"} | ${by} | ${mdEscape(f.suppression?.reason)} | \`${f.fid}\` |`);
    }
    lines.push("");
  }

  const errors = result.errors || [];
  if (errors.length > 0) {
    const probes = new Set(errors.map((e) => e.probe));
    lines.push("## Inconclusive probes");
    lines.push("");
    lines.push(`${probes.size} probe(s) could not complete. Their silence is not a clean result.`);
    lines.push("");
    lines.push("| Probe | URL | Error | Count |");
    lines.push("|-------|-----|-------|-------|");
    for (const e of errors) {
      lines.push(`| ${mdEscape(e.probe)} | \`${mdEscape(e.url)}\` | ${mdEscape(e.message)} | ${e.count || 1} |`);
    }
    lines.push("");
  }

  if (result.coverage) lines.push(...coverageMarkdown(result.coverage));
  if (result.giants) lines.push(...giantsMarkdown(result.giants));
  if (result.ai) lines.push(...aiMarkdown(result.ai));

  if (result.egress) {
    const e = result.egress;
    lines.push("## Network egress");
    lines.push("");
    lines.push(`- **Mode:** ${e.offline ? "--offline (scan target only)" : "online"}`);
    lines.push(`- **User-Agent:** \`${mdEscape(e.userAgent)}\``);
    if (e.thirdPartyHosts.length === 0) {
      lines.push(`- **Third-party hosts contacted:** none`);
    } else {
      lines.push(`- **Third-party hosts contacted:** ${e.thirdPartyHosts.map((h) => `\`${h.host}\` (${h.requests})`).join(", ")}`);
    }
    if (e.blocked.length > 0) {
      lines.push(`- **Blocked by --offline:** ${e.blocked.map((h) => `\`${h.host}\` (${h.requests})`).join(", ")}`);
    }
    if (result.retireDb) {
      lines.push(`- **Retire.js database:** ${result.retireDb.source === "snapshot" ? `vendored snapshot from ${result.retireDb.snapshotDate}` : "live"}`);
    }
    lines.push("");
  }

  const actionPlan = result.actionPlan || buildActionPlan(findings);
  if (actionPlan.length > 0) {
    lines.push(formatActionPlanMarkdown(actionPlan));
  }

  if (result.auditLoop) {
    lines.push(formatAuditLoopMarkdown(result.auditLoop));
  }

  lines.push("---");
  lines.push("");
  lines.push("*Authorized security testing only. See Penthera README for ethical use guidelines.*");
  lines.push("");
  lines.push(...footerLines(opts));

  return lines.join("\n");
}

export function writeMarkdownReport(result, filePath, opts = {}) {
  mkdirSync(dirname(filePath), { recursive: true });
  writeFileSync(filePath, formatMarkdownReport(result, opts));
}

export function markdownPathFromJson(jsonPath) {
  return jsonPath.replace(/\.json$/i, ".md");
}

/** "What was checked, and what was not": the repo scan's coverage ledger. */
export function coverageMarkdown(cov) {
  const L = ["## Coverage", ""];
  L.push("What the repo scan read, and what it did not. Files that no check read are not clean, only unchecked.");
  L.push("");
  L.push("| Check | Files read | Not read |");
  L.push("|---|---:|---|");
  for (const f of cov.families) {
    const skipped = Object.entries(f.skipped).map(([r, n]) => `${n} ${REASONS[r] || r}`).join("; ");
    L.push(`| ${f.label} | ${f.ran ? f.examined : "did not run"} | ${f.ran ? mdEscape(skipped || "none") : f.id === "routes" ? mdEscape(REASONS["no-api-surface"]) : "-"} |`);
  }
  for (const n of cov.notRun) L.push(`| ${n.label} | not part of a repo scan | run \`${n.command}\` |`);
  L.push("");
  if (cov.sourceFiles > 0) {
    L.push(`**Source files analysed by route analysis:** ${cov.sourceFilesAnalysed} of ${cov.sourceFiles}.`);
    const langs = cov.languages.map((l) => `${l.language} ${l.analysed}/${l.files}`).join(", ");
    L.push(`By language: ${langs}.`);
    L.push("");
  }
  if (cov.blindSpots.count > 0) {
    const why = Object.entries(cov.blindSpots.byReason).map(([r, n]) => `${n} ${REASONS[r] || r}`).join("; ");
    L.push(`<details><summary>${cov.blindSpots.count} source file${cov.blindSpots.count === 1 ? "" : "s"} not analysed by route analysis (${mdEscape(why)})</summary>`);
    L.push("");
    for (const p of cov.blindSpots.paths) L.push(`- \`${mdEscape(p)}\``);
    if (cov.blindSpots.count > cov.blindSpots.listed) L.push(`- …and ${cov.blindSpots.count - cov.blindSpots.listed} more (see the JSON report's \`coverage\`)`);
    L.push("");
    L.push("</details>");
    L.push("");
  }
  if (cov.excludedDirs.length) L.push(`Folders no check reads: ${cov.excludedDirs.map((d) => `\`${d}\``).join(", ")}.`, "");
  if (cov.truncated) L.push("The ledger stopped at 50,000 files; counts above cover those files only.", "");
  return L;
}

/** AI mode: the route, what the model read, and its findings by what Penthera made of them. */
export function aiMarkdown(ai) {
  const L = ["## AI mode", ""];
  if (ai.ran === false) {
    L.push(`AI mode did not run: ${mdEscape(ai.reason)}`, "");
    return L;
  }
  const where = ai.route === "local"
    ? "on this computer (Ollama on 127.0.0.1). Nothing was sent off it."
    : `on ${ai.forwardedTo}, through Ollama on 127.0.0.1. Code was sent to ${ai.forwardedTo}.`;
  L.push(`Model \`${mdEscape(ai.model.name)}\` ran ${where} Consent: ${mdEscape(ai.consent.via)} (text version ${ai.consent.textVersion}). Hosts Penthera contacted: ${ai.hostsContacted.map((h) => `\`${h}\``).join(", ")}.`);
  L.push("");
  L.push(`The model read ${ai.units.examined} of ${ai.units.units} code parts${ai.partial ? `; the run is **partial** (${mdEscape(ai.stopReason)}), and ${ai.units.notExamined} parts were not read` : ""}. Tokens: ${ai.tokens.prompt + ai.tokens.output}. Prompt \`${ai.promptHash.slice(0, 12)}\` (version ${ai.promptVersion}).`);
  L.push("");
  L.push("| Result | Findings |", "|---|---:|");
  L.push(`| Confirmed by a Penthera rule (marked in Findings) | ${ai.counts["confirmed-by-rule"]} |`);
  L.push(`| Model-proposed, unverified | ${ai.counts.unverified} |`);
  L.push(`| Not kept: pointed at a line or file that is not there | ${ai.counts["location-not-found"] + ai.counts["out-of-scope"]} |`);
  L.push("");
  if (ai.findings.length) {
    L.push("### Model-proposed, unverified", "");
    L.push("No Penthera rule confirmed these. They are a model's claims: read the code before acting on them. They are not counted in the summary and never change the exit code.", "");
    L.push("| Finding | Location | Class | Claimed severity |", "|---|---|---|---|");
    for (const f of ai.findings) L.push(`| ${mdEscape(f.title)} | \`${mdEscape(f.url)}:${f.line}\` | ${mdEscape(f.class)} | ${mdEscape(f.severity)} |`);
    L.push("");
  }
  return L;
}
