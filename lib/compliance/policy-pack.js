/**
 * Proportionate policy-pack generator.
 *
 * NIS2 expects an in-scope entity to have basic written policies. For a small
 * company these should be short, real, and used — not enterprise binders. This
 * module emits editable Markdown starting points for the core policies, pre-
 * filled where the scan/self-assessment gives us something concrete (the
 * incident plan carries the jurisdiction's real deadlines; the vulnerability
 * policy references the Penthera scan cadence).
 *
 * These are TEMPLATES, not legal documents. Every file says so.
 */

function header(title, ctx) {
  return [
    `# ${title}`,
    "",
    `**Organisation:** ${ctx.org}  `,
    `**Owner:** _(name a responsible person)_  `,
    `**Version:** 0.1 (draft)  `,
    `**Last reviewed:** ${ctx.date}  `,
    `**Next review:** _(set a date — at least yearly)_`,
    "",
  ].join("\n");
}

function footer() {
  return [
    "",
    "---",
    "",
    "> **Editable template — not legal advice and not a certification.** Adapt it to",
    "> how your organisation actually works, then keep it short and used. An honest",
    "> two-page policy that people follow beats a long one nobody reads.",
    "> Generated by Penthera.",
    "",
  ].join("\n");
}

/** Optional one-line note about current readiness for this measure. */
function readinessNote(ctx, measure) {
  const m = ctx.readiness?.measures?.find((x) => x.id === measure);
  if (!m) return "";
  const gaps = (m.gaps || []).filter((g) => g.type !== "unanswered").map((g) => g.question);
  const gapLine = gaps.length ? ` Gaps to close: ${gaps.join("; ")}.` : "";
  return `\n> _Current readiness for this measure (from your latest Penthera run): **${m.status}**.${gapLine}_\n`;
}

