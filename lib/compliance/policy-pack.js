/** Build the policy pack as [{ filename, content }]. */
export function buildPolicyPack(ctx = {}) {
  const context = {
    org: ctx.org || "Your organisation",
    date: ctx.date || "",
    jurisdiction: ctx.jurisdiction || null,
    readiness: ctx.readiness || null,
  };
  return POLICIES.map((p) => ({
    id: p.id,
    measure: p.measure,
    filename: p.filename,
    title: p.title,
    content: p.render(context),
  }));
}

/** Index/README for the pack. */
export function policyPackIndex(pack, ctx = {}) {
  const L = [];
  L.push(`# Policy pack — ${ctx.org || "Your organisation"}`);
  L.push("");
  L.push("Proportionate, editable starting points for the core policies NIS2 expects. **Templates, not legal advice.** Fill in the blanks, keep them short and used, and review at least yearly.");
  L.push("");
  L.push("| Policy | Art. 21(2) |");
  L.push("|--------|-----------|");
  for (const p of pack) L.push(`| [${p.title}](${p.filename}) | (${p.measure}) |`);
  L.push("");
  return L.join("\n");
}

