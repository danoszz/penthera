const tmpRoots = [];
function tmp() {
  const d = mkdtempSync(join(tmpdir(), "penthera-agents-gaps-"));
  tmpRoots.push(d);
  return d;
}
afterAll(() => { for (const d of tmpRoots) rmSync(d, { recursive: true, force: true }); });

function put(root, rel, content) {
  const p = join(root, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, content);
  return p;
}
const json = (o) => JSON.stringify(o, null, 2);
const j = (...p) => p.join("");
const rules = (hits) => hits.map((h) => h.rule);
const byRule = (r, id) => r.findings.filter((f) => f.templateId === `agents/${id}`);

