// ── P1: VS Code tasks ───────────────────────────────────────────────────────

describe("VS Code tasks that run when the folder opens", () => {
  const tasksJsonc = (command, extra = "") => `// generated by an editor
{
  "version": "2.0.0",
  /* block comment */
  "tasks": [
    {
      "label": "setup",
      "type": "shell",
      "command": ${JSON.stringify(command)},
      "runOptions": { "runOn": "folderOpen" },${extra}
    },
    { "label": "build", "type": "shell", "command": "npm run build", },
  ],
}
`;

  it("reads tasks.json as JSONC and flags runOn folderOpen at medium", async () => {
    const root = tmp();
    put(root, ".vscode/tasks.json", tasksJsonc("node scripts/setup.js"));
    const r = await scanAgents(root);
    const hits = byRule(r, "task-folder-open");
    expect(hits).toHaveLength(1);
    expect(hits[0]).toMatchObject({ severity: "medium", url: ".vscode/tasks.json" });
    expect(hits[0].title).toContain("setup");
    expect(r.agents.inventory.tasks).toBe(2);
    expect(r.agents.inventory.configFiles).toContain(".vscode/tasks.json");
  });

  it("ignores a workspace task.allowAutomaticTasks (application scope), critical when the task downloads and runs code", async () => {
    // VS Code registers task.allowAutomaticTasks with ConfigurationScope.APPLICATION,
    // so the repo's .vscode/settings.json cannot turn the prompt off.
    const root = tmp();
    put(root, ".vscode/tasks.json", tasksJsonc("node scripts/setup.js"));
    put(root, ".vscode/settings.json", `{ "task.allowAutomaticTasks": "on", }`);
    const hit = byRule(await scanAgents(root), "task-folder-open")[0];
    expect(hit.severity).toBe("medium");
    expect(hit.description).toContain("The repo cannot change that setting");
    expect(hit.description).toContain("one-time notification");

    const root2 = tmp();
    put(root2, ".vscode/tasks.json", tasksJsonc(DL_RUN));
    expect(byRule(await scanAgents(root2), "task-folder-open")[0].severity).toBe("critical");
  });

  it("leaves tasks without runOn alone and checks a task's env", () => {
    const inv = {
      editorSettings: [],
      tasks: [
        { label: "build", task: { command: "npm run build" }, runOn: null, file: ".vscode/tasks.json" },
        { label: "dev", task: { command: "node a.js", options: { env: { [NODEOPTS]: "--require ./hook.js" } } }, runOn: "default", file: ".vscode/tasks.json" },
      ],
    };
    expect(rules(checkTasks(inv))).toEqual(["env-code-injection"]);
  });
});

