#!/usr/bin/env python3
"""Rebuild src/card/font.js, the Departure Mono pixel table the share card draws with.

    python3 scripts/card/build-font.py

Departure Mono is a pixel font on a 50-unit grid (7 x 14 px cells), so each
glyph is sampled once at its pixel centres. Needs fontTools and brotli; the
output is committed, so npm users never run this.
"""
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.recordingPen import RecordingPen

ROOT = Path(__file__).resolve().parents[2]
FONT = ROOT / "src/ui/static/fonts/DepartureMono-Regular.woff2"
OUT = ROOT / "src/card/font.js"
CHARS = [chr(c) for c in range(32, 127)] + list("·×→←•…–░▒▓█▀▄■□▪↗")
UNIT, COLS, ASC, ROWS = 50, 7, 11, 14

f = TTFont(str(FONT))
gs, cmap = f.getGlyphSet(), f.getBestCmap()

def polys(ch):
    pen = RecordingPen()
    gs[cmap[ord(ch)]].draw(pen)
    out, cur = [], []
    for op, pts in pen.value:
        if op == "moveTo":
            cur = [pts[0]]
        elif op == "lineTo":
            cur.append(pts[0])
        elif op in ("closePath", "endPath"):
            if cur: out.append(cur)
            cur = []
        else:
            raise SystemExit(f"{ch!r}: curve {op} in a pixel font")
    return out

def winding(px, py, contours):
    w = 0
    for c in contours:
        for i in range(len(c)):
            (x1, y1), (x2, y2) = c[i], c[(i + 1) % len(c)]
            if y1 <= py < y2 and px < x1 + (py - y1) * (x2 - x1) / (y2 - y1): w += 1
            elif y2 <= py < y1 and px < x1 + (py - y1) * (x2 - x1) / (y2 - y1): w -= 1
    return w

rows = []
for ch in CHARS:
    cs = polys(ch)
    bits = []
    for r in range(ROWS):
        y = (ASC - r) * UNIT - UNIT / 2
        v = 0
        for col in range(COLS):
            if winding(col * UNIT + UNIT / 2, y, cs): v |= 1 << (COLS - 1 - col)
        bits.append(f"{v:02x}")
    rows.append((ch, "".join(bits)))

body = ",\n".join(f"  {ord(ch)}: \"{b}\"" for ch, b in rows)
OUT.write_text(f'''/**
 * Departure Mono as a pixel table, for the share card (src/card). Generated by
 * scripts/card/build-font.py from src/ui/static/fonts/DepartureMono-Regular.woff2;
 * do not edit by hand.
 *
 * Departure Mono, copyright 2022-2024 Helena Zhang, SIL Open Font License 1.1:
 * src/ui/static/fonts/DepartureMono-LICENSE.txt.
 *
 * Each glyph is {COLS} x {ROWS} pixels, the baseline under row {ASC - 1}: one hex byte per row,
 * high bit on the left.
 */
export const CELL = {{ w: {COLS}, h: {ROWS}, ascent: {ASC} }};

export const GLYPHS = {{
{body},
}};
''')
print(f"{len(rows)} glyphs -> {OUT.relative_to(ROOT)}")
